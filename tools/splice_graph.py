#!/usr/bin/env python3
"""Build the container the port audit says we are missing, out of bytes we already hold.

WHY THESE TWO ARRAYS AND NOT A CAPTURE.  The live start lists (read out of the vendor's
in-band PREPARE/START bodies in logs/gpr-both-20261105-223253.txt) name the CURRENT
subgraph keys.  Scored against those:
  g_graph_ukee_current (2960) - current keys, walks with slack 0, and its stream
      subgraph 0xb0000023 already carries WR 0x40bd / 0x40be / PCM_DEC 0x40bf /
      PCM_CNV 0x40c0 / 0x40c1 exactly as the vendor does, BUT its device subgraph
      0xb0000002 has no TDM_SINK, no MFC and no AW - so from PCM_CNV onwards that
      container never reaches the TDM hardware.
  g_graph_vendor4 (2724) - its entry[0] (0xb0000002, 860 B) and entry[2]
      (0xb0000024, 300 B) walk self-consistently and carry the hardware side
      (SAL 0x4012, DATA_LOGGING 0x4007, SPLITTER 0x418e, TDM_SINK 0x428f,
      MUX_DEMUX 0x4006, MFC 0x48ba, 0x10013d01/0x42d3); its entry[1] names
      0xb0000081, which appears in no live start list (previous generation), and
      its entry[3] overruns the array by 4 bytes.
So the splicer takes the CURRENT container and grafts the vendor's device entry over
our device entry, i.e. conversion chain from our own rebuild, hardware chain from the
vendor's bytes, and nothing is invented in between.

This script only writes a file under docs/data and prints the C array; it does not
touch the driver, does not boot, and refuses to emit if the sizes do not close.
"""
import re
import struct
import sys

SRC = "../chain-tree/bsd/dev/sweet_glink.c"
OUT = "docs/data/g_graph_ukee_hwspliced.txt"


def blob(name):
    src = open(SRC, errors="replace").read()
    m = re.search(r"static const uint8_t %s\[(\d+)\] = \{(.*?)\n\};" % name, src, re.S)
    if not m:
        sys.exit(f"FATAL: {name} not found in {SRC}")
    d = bytes(int(x, 16) for x in re.findall(r"0x([0-9a-fA-F]{1,2})", m.group(2)))
    if int(m.group(1)) != len(d):
        sys.exit(f"FATAL: {name} declared {m.group(1)}, parsed {len(d)}")
    return d


def entries(d):
    """(key, body_bytes) per entry; the index is {u32 total, u32 count} then
    per entry {u32 key, u32 size, size bytes}."""
    u = lambda o: struct.unpack_from("<I", d, o)[0]
    n, o = u(4), 8
    out = []
    for _ in range(n):
        key, sz = u(o), u(o + 4)
        out.append((key, d[o + 8:o + 8 + sz]))
        o += 8 + sz
    return o, out


def build():
    cur = blob("g_graph_ukee_current")
    ven = blob("g_graph_vendor4")
    consumed_c, ents_c = entries(cur)
    consumed_v, ents_v = entries(ven)
    print(f"current: {len(cur)} B, index consumed {consumed_c}, slack {len(cur) - consumed_c}")
    print(f"vendor : {len(ven)} B, index consumed {consumed_v}, slack {len(ven) - consumed_v}"
          f"  (negative = its own index overruns the array)")
    if len(cur) - consumed_c != 0:
        sys.exit("REFUSING: the current container is not self-consistent, nothing to graft onto")

    keys_c = [k for k, _ in ents_c]
    keys_v = [k for k, _ in ents_v]
    print("current keys:", " ".join(f"{k:#x}" for k in keys_c))
    print("vendor  keys:", " ".join(f"{k:#x}" for k in keys_v))
    try:
        i_dev = keys_c.index(0xb0000002)
        j_dev = keys_v.index(0xb0000002)
    except ValueError:
        sys.exit("REFUSING: the device subgraph 0xb0000002 is missing on one side")
    old = ents_c[i_dev][1]
    new = ents_v[j_dev][1]
    print(f"\ngrafting entry[0] 0xb0000002: our body {len(old)} B -> vendor body {len(new)} B")

    out = bytearray()
    for idx, (key, body) in enumerate(ents_c):
        body = new if idx == i_dev else body
        out += struct.pack("<II", key, len(body)) + body
    head = struct.pack("<II", 8 + len(out), len(ents_c))
    total = head + bytes(out)
    # 8-align the whole payload the way both sources do
    while len(total) % 8:
        total += b"\x00"
    total = struct.pack("<II", len(total), len(ents_c)) + bytes(out) + b"\x00" * (
        (-len(head) - len(out)) % 8)
    consumed, back = entries(total)
    print(f"result  : {len(total)} B, index consumed {consumed}, slack {len(total) - consumed}")
    print("result keys:", " ".join(f"{k:#x}({len(b)})" for k, b in back))
    if len(total) - consumed not in (0, 4):
        sys.exit(f"REFUSING: result is not self-consistent (slack {len(total) - consumed})")

    with open(OUT, "w") as h:
        h.write(f"/* generated by tools/splice_graph.py - {len(total)} bytes, slack "
                f"{len(total) - consumed}\n"
                " * g_graph_ukee_current with its device subgraph 0xb0000002 replaced by\n"
                " * g_graph_vendor4's entry for the same key (TDM_SINK/MFC/AW hardware side).\n"
                " */\nstatic const uint8_t g_graph_ukee_hwspliced[%d] = {\n" % len(total))
        for i in range(0, len(total), 12):
            h.write("\t" + " ".join("0x%02x," % b for b in total[i:i + 12]) + "\n")
        h.write("};\n")
    print(f"wrote   : {OUT}")


build()
